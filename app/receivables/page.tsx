const inputBase = 'w-full px-3 py-2 border rounded-lg text-sm focus:outline-none focus:ring-2 focus:ring-blue-500 bg-white text-gray-900'

function inputClass(field: string, errors: Record<string, string>) {
  return `${inputBase} ${errors[field] ? 'border-red-400' : 'border-gray-300'}`
}

