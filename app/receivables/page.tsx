interface AddInvoiceModalProps {
  onClose: () => void
  onSaved: () => void
}

function AddInvoiceModal({ onClose, onSaved }: AddInvoiceModalProps) {
  const { t } = useLanguage()
  const [form, setForm] = useState({
    invoiceCode: '', customerName: '', address: '', invoiceDate: toInputDate(todayDDMMYYYY()), dueDays: '30', discount: '0', totalAmount: '',
  })
  const [codeAutoGenerated, setCodeAutoGenerated] = useState(true)
  const [loadingCode, setLoadingCode] = useState(false)
  const [errors, setErrors] = useState<Record<string, string>>({})
  const [saving, setSaving] = useState(false)
  const [saveError, setSaveError] = useState('')

  useEffect(() => {
    if (!codeAutoGenerated) return
    const ddmmyyyy = fromInputDate(form.invoiceDate)
    if (!ddmmyyyy) return
    let cancelled = false
    setLoadingCode(true)
    fetch(`/api/receivables/next-code?date=${encodeURIComponent(ddmmyyyy)}`)
      .then((r) => (r.ok ? r.json() : null))
      .then((data) => { if (!cancelled && data?.code) setForm((prev) => ({ ...prev, invoiceCode: data.code })) })
      .finally(() => { if (!cancelled) setLoadingCode(false) })
    return () => { cancelled = true }
  }, [form.invoiceDate, codeAutoGenerated])

  function validate() {
    const e: Record<string, string> = {}
    if (!form.invoiceCode.trim()) e.invoiceCode = t('ar.modal.addInvoice.code') + ' required'
    if (!form.customerName.trim()) e.customerName = t('ar.modal.addInvoice.customer') + ' required'
    if (!form.invoiceDate) e.invoiceDate = t('ar.modal.addInvoice.invoiceDate') + ' required'
    if (!form.dueDays || parseInt(form.dueDays) <= 0) e.dueDays = t('ar.modal.addInvoice.dueDays') + ' required'
    if (!form.totalAmount || parseFloat(form.totalAmount) <= 0) e.totalAmount = t('ar.modal.addInvoice.total') + ' required'
    return e
  }

  async function handleSubmit(e: React.FormEvent) {
    e.preventDefault()
    const errs = validate()
    if (Object.keys(errs).length > 0) { setErrors(errs); return }
    setSaving(true)
    setSaveError('')
    try {
      const invoiceDate = fromInputDate(form.invoiceDate)
      const dueDate = addDays(invoiceDate, parseInt(form.dueDays))
      const res = await fetch('/api/receivables', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          invoiceCode: form.invoiceCode,
          customerName: form.customerName,
          address: form.address,
          discount: form.discount,
          invoiceDate,
          dueDate,
          totalAmount: form.totalAmount,
        }),
      })
      if (!res.ok) throw new Error()
      onSaved()
    } catch {
      setSaveError(t('ar.saveError'))
    } finally {
      setSaving(false)
    }
  }

  const invoiceDateDDMM = fromInputDate(form.invoiceDate)
  const computedDue = invoiceDateDDMM && parseInt(form.dueDays) > 0
    ? addDays(invoiceDateDDMM, parseInt(form.dueDays))
    : null

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/40 p-4">
      <div className="bg-white rounded-xl shadow-xl w-full max-w-lg">
        <div className="flex items-center justify-between px-6 py-4 border-b border-gray-200">
          <h2 className="text-base font-semibold text-gray-900">{t('ar.modal.addInvoice.title')}</h2>
          <button onClick={onClose} className="text-gray-400 hover:text-gray-600 text-xl leading-none">×</button>
        </div>
        <form onSubmit={handleSubmit} className="px-6 py-4 space-y-4">
          <div>
            <label className="block text-xs font-medium text-gray-700 mb-1">{t('ar.modal.addInvoice.code')}</label>
            <input
              className={inputClass('invoiceCode', errors)}
              placeholder={loadingCode ? t('common.generating') : t('ar.modal.addInvoice.ph.code')}
              value={form.invoiceCode}
              onChange={(e) => { setCodeAutoGenerated(false); setForm({ ...form, invoiceCode: e.target.value }) }}
            />
            {errors.invoiceCode && <p className="text-xs text-red-500 mt-1">{errors.invoiceCode}</p>}
          </div>
          <div>
            <label className="block text-xs font-medium text-gray-700 mb-1">{t('ar.modal.addInvoice.customer')}</label>
            <input
              className={inputClass('customerName', errors)}
              placeholder={t('ar.modal.addInvoice.ph.customer')}
              value={form.customerName}
              onChange={(e) => setForm({ ...form, customerName: e.target.value })}
            />
            {errors.customerName && <p className="text-xs text-red-500 mt-1">{errors.customerName}</p>}
          </div>
          <div>
            <label className="block text-xs font-medium text-gray-700 mb-1">{t('ar.modal.addInvoice.address')}</label>
            <input
              className={inputClass('address', errors)}
              placeholder={t('ar.modal.addInvoice.ph.address')}
              value={form.address}
              onChange={(e) => setForm({ ...form, address: e.target.value })}
            />
          </div>
          <div className="grid grid-cols-2 gap-4">
            <div>
              <label className="block text-xs font-medium text-gray-700 mb-1">{t('ar.modal.addInvoice.invoiceDate')}</label>
              <input
                type="date"
                className={inputClass('invoiceDate', errors)}
                value={form.invoiceDate}
                onChange={(e) => setForm({ ...form, invoiceDate: e.target.value })}
              />
              {errors.invoiceDate && <p className="text-xs text-red-500 mt-1">{errors.invoiceDate}</p>}
            </div>
            <div>
              <label className="block text-xs font-medium text-gray-700 mb-1">{t('ar.modal.addInvoice.dueDays')}</label>
              <input
                type="number"
                min="1"
                className={inputClass('dueDays', errors)}
                placeholder={t('ar.modal.addInvoice.ph.dueDays')}
                value={form.dueDays}
                onChange={(e) => setForm({ ...form, dueDays: e.target.value })}
              />
              {errors.dueDays && <p className="text-xs text-red-500 mt-1">{errors.dueDays}</p>}
              {computedDue && (
                <p className="text-xs text-gray-400 mt-1">Due: {computedDue}</p>
              )}
            </div>
          </div>
          <div className="grid grid-cols-2 gap-4">
            <div>
              <label className="block text-xs font-medium text-gray-700 mb-1">{t('ar.modal.addInvoice.total')}</label>
              <input
                type="number"
                min="1"
                className={inputClass('totalAmount', errors)}
                placeholder={t('ar.modal.addInvoice.ph.total')}
                value={form.totalAmount}
                onChange={(e) => setForm({ ...form, totalAmount: e.target.value })}
              />
              {errors.totalAmount && <p className="text-xs text-red-500 mt-1">{errors.totalAmount}</p>}
            </div>
            <div>
              <label className="block text-xs font-medium text-gray-700 mb-1">{t('ar.modal.addInvoice.discount')}</label>
              <input
                type="number"
                min="0"
                max="100"
                className={inputClass('discount', errors)}
                placeholder={t('ar.modal.addInvoice.ph.discount')}
                value={form.discount}
                onChange={(e) => setForm({ ...form, discount: e.target.value })}
              />
            </div>
          </div>
          {saveError && <p className="text-sm text-red-600">{saveError}</p>}
          <div className="flex justify-end gap-3 pt-2">
            <button type="button" onClick={onClose} className="px-4 py-2 text-sm text-gray-600 hover:text-gray-800 transition-colors">
              {t('common.cancel')}
            </button>
            <button
              type="submit"
              disabled={saving}
              className="px-4 py-2 text-sm font-medium bg-blue-700 text-white rounded-lg hover:bg-blue-800 disabled:opacity-60 disabled:cursor-not-allowed transition-colors"
            >
              {saving ? t('common.saving') : t('common.save')}
            </button>
          </div>
        </form>
      </div>
    </div>
  )
}

